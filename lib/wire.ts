/** One provider answer as an OpenAI SSE stream: role chunk, text, finish, usage, [DONE]. */
export async function* openAIStreamFromParsed(answer: ParsedAnswer, model: string): AsyncGenerator<string> {
  const chunk = (delta: Json, finish: string | null): Json => ({
    id: 'chatcmpl-aggregate',
    object: 'chat.completion.chunk',
    created: FIXED_OPENAI_CREATED,
    model,
    choices: [{ index: 0, delta, finish_reason: finish }],
  });
  yield sseEvent(null, chunk({ role: 'assistant', content: '' }, null));
  for (const piece of textPieces(answer.text)) yield sseEvent(null, chunk({ content: piece }, null));
  yield sseEvent(null, chunk({}, stopForClient(answer.stopReason, 'openai')));
  yield sseEvent(null, {
    id: 'chatcmpl-aggregate',
    object: 'chat.completion.chunk',
    created: FIXED_OPENAI_CREATED,
    model,
    choices: [],
    usage: { prompt_tokens: answer.inputTokens, completion_tokens: answer.outputTokens, total_tokens: answer.inputTokens + answer.outputTokens },
  });
  yield 'data: [DONE]\n\n';
}

/** One provider answer as an Anthropic SSE stream: start, text, stop, usage, end. */
export async function* anthropicStreamFromParsed(answer: ParsedAnswer, model: string): AsyncGenerator<string> {
  yield sseEvent('message_start', {
    type: 'message_start',
    message: {
      id: 'msg_aggregate',
      type: 'message',
      role: 'assistant',
      model,
      content: [],
      stop_reason: null,
      stop_sequence: null,
      usage: { input_tokens: answer.inputTokens, output_tokens: 0 },
    },
  });
  yield sseEvent('content_block_start', { type: 'content_block_start', index: 0, content_block: { type: 'text', text: '' } });
  for (const piece of textPieces(answer.text)) {
    yield sseEvent('content_block_delta', { type: 'content_block_delta', index: 0, delta: { type: 'text_delta', text: piece } });
  }
  yield sseEvent('content_block_stop', { type: 'content_block_stop', index: 0 });
  yield sseEvent('message_delta', {
    type: 'message_delta',
    delta: { stop_reason: stopForClient(answer.stopReason, 'anthropic'), stop_sequence: null },
    usage: { output_tokens: answer.outputTokens },
  });
  yield sseEvent('message_stop', { type: 'message_stop' });
}
